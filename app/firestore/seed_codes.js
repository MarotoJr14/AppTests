function uniqueNormalizedCodes() {
  const set = new Set();
  for (const raw of CODES) {
    const code = String(raw).trim().toUpperCase();
    if (code) set.add(code);
  }
  return Array.from(set);
}

async function seedCodes() {
  const codes = uniqueNormalizedCodes();
  console.log(`Seeding ${codes.length} registration codes...`);

  // Firestore batch limit is 500 writes.
  const batchSize = 450;
  let written = 0;

  for (let i = 0; i < codes.length; i += batchSize) {
    const batch = db.batch();
    const slice = codes.slice(i, i + batchSize);
    for (const code of slice) {
      const ref = db.collection('registrationCodes').doc(code);
      batch.set(
        ref,
        {
          code,
          available: true,
          assignedEmail: null,
          usedAt: null,
          reservedForEmail: null,
          reservedUntil: null,
          updatedAt: admin.firestore.FieldValue.serverTimestamp(),
        },
        { merge: true },
      );
    }
    await batch.commit();
    written += slice.length;
    console.log(`✓ ${written}/${codes.length}`);
  }

  console.log('Done.');
  process.exit(0);
}

seedCodes().catch((e) => {
  console.error(e);
  process.exit(1);
});

